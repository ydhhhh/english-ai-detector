def _label(value):
    return "" if value is None else str(value)


def _trusted(value):
    if isinstance(value, (bool, np.bool_)):
        return bool(value)
    if isinstance(value, (int, np.integer)):
        return int(value) == 1
    return isinstance(value, str) and value.casefold() in ("true", "1")


def _known_label(value):
    return _label(value).casefold() not in UNKNOWN_LABELS


def _texts(records):
    values = [row["text"] for row in records]
    if not all(isinstance(text, str) for text in values):
        raise TypeError("record texts must be strings")
    return values


def _array(records, field, default=""):
    return np.asarray([_label(row.get(field, default)) for row in records], dtype=str)


def _check_records(records, purpose):
    if not records:
        raise ValueError(f"{purpose} records are empty")
    for row in records:
        if not isinstance(row.get("text"), str) or not row["text"].strip():
            raise ValueError(f"{purpose} contains missing/empty text")
        if row.get("y_ai") not in (0, 1):
            raise ValueError(f"{purpose} y_ai must be 0 for human and 1 for AI")
        if row.get("id") is None:
            raise ValueError(f"{purpose} contains missing id")
        if int(row["y_ai"]) == 0 and (_trusted(row.get("mask_family")) or _trusted(row.get("mask_model"))):
            raise ValueError(f"{purpose} human row has a true attribution mask")


def assert_disjoint(left, right, left_name, right_name):
    """Refuse known group/content/ID overlap before training or calibration."""
    for key in ("id", "group_id", "normalized_sha256"):
        lset = {_label(x.get(key)) for x in left if x.get(key) not in (None, "")}
        rset = {_label(x.get(key)) for x in right if x.get(key) not in (None, "")}
        if lset & rset:
            raise ValueError(f"{left_name}/{right_name} overlap in {key}: {len(lset & rset)} shared values")


def _bounded(text, max_chars):
    if max_chars and len(text) > max_chars:
        left = max_chars // 2
        return text[:left] + "\n\n" + text[-(max_chars-left):]
    return text


def _window_plan(texts,config):
    """Cover every source character; overlap contributes context, not weight."""
    limit=config.max_chars_per_text
    if not 0 < config.window_stride_fraction <= 1:
        raise ValueError("window_stride_fraction must be in (0,1]")
    stride=max(1,int(limit*config.window_stride_fraction)) if limit else None
    windows=[];owners=[];weights=[];counts=[];input_chars=[]
    for owner,text in enumerate(texts):
        if not isinstance(text,str):raise TypeError("all texts must be strings")
        input_chars.append(len(text))
        if not limit or len(text)<=limit:
            windows.append(text);owners.append(owner);weights.append(max(1,len(text)));counts.append(1)
            continue
        previous_end=0;count=0
        for start in range(0,len(text),stride):
            end=min(len(text),start+limit)
            new_chars=end-previous_end
            if new_chars>0:
                windows.append(text[start:end]);owners.append(owner);weights.append(new_chars);count+=1
            previous_end=end
            if end==len(text):break
        counts.append(count)
    input_chars=np.asarray(input_chars,dtype=np.int64)
    counts=np.asarray(counts,dtype=np.int32)
    summary={"documents":len(texts),"windows":len(windows),"input_characters":int(input_chars.sum()),
        "covered_characters":int(input_chars.sum()),"source_character_coverage":1.,
        "documents_with_multiple_windows":int((counts>1).sum()),"max_windows_per_document":int(counts.max()) if len(counts) else 0,
        "window_size_characters":limit,"stride_characters":stride,
        "aggregation":"mean raw scores weighted by newly covered source characters; all source characters covered"}
    return {"texts":windows,"owners":np.asarray(owners,dtype=np.int64),"weights":np.asarray(weights,dtype=np.float64),
        "document_count":len(texts),"counts":counts,"input_chars":input_chars,"summary":summary}


def _aggregate_window_scores(scores,plan):
    scores=np.asarray(scores,dtype=np.float64)
    output=np.zeros((plan["document_count"],scores.shape[1]),dtype=np.float64)
    np.add.at(output,plan["owners"],scores*plan["weights"][:,None])
    denominators=np.bincount(plan["owners"],weights=plan["weights"],minlength=plan["document_count"])
    return output/np.maximum(1.,denominators)[:,None]


def _style_rows(texts):
    """Only row-local quantities; standardization is learned once on train."""
    rows = []
    for text in texts:
        words = WORD.findall(text)
        lowered = [w.casefold() for w in words]
        n, w = max(1, len(text)), max(1, len(words))
        lengths = np.asarray([len(word) for word in words], dtype=float)
        sentence_lengths = [len(WORD.findall(s)) for s in SENTENCE.findall(text) if WORD.search(s)]
        sl = np.asarray(sentence_lengths or [0], dtype=float)
        lines = text.splitlines() or [""]
        counts = Counter(lowered)
        row = [
            math.log1p(len(text)), math.log1p(len(words)), math.log1p(len(lines)),
            len(counts)/w, sum(c == 1 for c in counts.values())/w,
            float(lengths.mean()) if len(lengths) else 0., float(lengths.std()) if len(lengths) else 0.,
            float(sl.mean()), float(sl.std()), sum(x in FUNCTION_WORDS for x in lowered)/w,
            sum(c.isupper() for c in text)/n, sum(c.isdigit() for c in text)/n,
            sum(c.isspace() for c in text)/n, text.count("\n")/n,
            sum(c in ".,;:!?" for c in text)/n, text.count("!")/n, text.count("?")/n,
            sum(c in "\"'‘’“”" for c in text)/n,
            sum(c in "()[]{}" for c in text)/n, text.count("-")/n,
            sum(c in "—–" for c in text)/n, sum(c in "*#`" for c in text)/n,
            sum(c in "•" for c in text)/n,
            sum(bool(re.match(r"\s*(?:[-*•]|\d+[.)])\s+", line)) for line in lines)/max(1, len(lines)),
            sum(len(word) <= 3 for word in words)/w,
            sum(len(word) >= 9 for word in words)/w,
            sum(c > 127 for c in map(ord, text))/n,
            len(re.findall(r"\s{2,}", text))/n,
        ]
        rows.append(row)
    return np.asarray(rows, dtype=np.float32).reshape((-1, 28))


class MultiChannelFeatures:
    def __init__(self, config):
        self.config = config

    def _prepare(self, texts):
        if isinstance(texts, str):
            raise TypeError("pass a sequence of texts, not a single string")
        values = list(texts)
        if not all(isinstance(text, str) for text in values):
            raise TypeError("all texts must be strings")
        return [_bounded(text, self.config.max_chars_per_text) for text in values]

    @staticmethod
    def _channel(texts, name):
        if name == "shape":
            return [shape_text(text) for text in texts]
        if name == "function":
            return [function_text(text) for text in texts]
        return texts

    def fit_transform(self, texts):
        started = time.monotonic()
        texts = self._prepare(texts)
        self.vectorizers_ = {}
        self.channel_weights_ = {}
        self.feature_counts_ = {}
        blocks = []
        for name, analyzer, ngrams, limit, weight in FEATURE_CHANNELS:
            options = dict(analyzer=analyzer, ngram_range=ngrams, lowercase=False,
                sublinear_tf=True, min_df=min(self.config.min_df, max(1, len(texts)//3)),
                max_features=max(32, int(limit*self.config.feature_scale)), dtype=np.float32)
            if analyzer == "word":
                options["token_pattern"] = r"(?u)\b\w+\b|[^\w\s]"
            vectorizer = TfidfVectorizer(**options)
            try:
                block = vectorizer.fit_transform(self._channel(texts, name))
            except ValueError as exc:
                if "empty vocabulary" in str(exc) or "After pruning" in str(exc):
                    self.feature_counts_[name] = 0
                    continue
                raise
            self.vectorizers_[name] = vectorizer
            self.channel_weights_[name] = weight
            self.feature_counts_[name] = int(block.shape[1])
            blocks.append(block * weight)
        style = _style_rows(texts)
        self.style_scaler_ = StandardScaler().fit(style)
        style = np.clip(self.style_scaler_.transform(style), -8., 8.)
        blocks.append(sparse_normalize(csr_matrix(style), norm="l2", copy=False) * .35)
        self.feature_counts_["numeric_style"] = 28
        matrix = hstack(blocks, dtype=np.float32, format="csr")
        self.n_features_ = matrix.shape[1]
        self.fit_info_ = {"channels": self.feature_counts_, "rows": len(texts),
            "features": int(matrix.shape[1]), "nnz": int(matrix.nnz),
            "csr_bytes": int(matrix.data.nbytes+matrix.indices.nbytes+matrix.indptr.nbytes),
            "fit_seconds": time.monotonic()-started,
            "max_chars_per_text": self.config.max_chars_per_text,
            "training_long_text_policy": "deterministic head+tail if over limit; development, calibration and inference instead use complete overlapping windows"}
        return matrix

    def transform(self, texts):
        texts = self._prepare(texts)
        if not texts:
            return csr_matrix((0, self.n_features_), dtype=np.float32)
        blocks = [vectorizer.transform(self._channel(texts, name))*self.channel_weights_[name]
            for name, vectorizer in self.vectorizers_.items()]
        style = np.clip(self.style_scaler_.transform(_style_rows(texts)), -8., 8.)
        blocks.append(sparse_normalize(csr_matrix(style), norm="l2", copy=False)*.35)
        return hstack(blocks, dtype=np.float32, format="csr")


def _head_mask(records, task):
    if task == "binary":
        return np.ones(len(records), dtype=bool)
    return np.asarray([int(row["y_ai"]) == 1 and _trusted(row.get("mask_"+task))
        and (_known_label(row.get(task)) or (task == "family" and _label(row.get(task)) == "Other"))
        for row in records], dtype=bool)


def _targets(records, task):
    return np.asarray([int(row["y_ai"]) for row in records], dtype=np.int64) if task == "binary" else _array(records, task)


def _score_matrix(model, matrix):
    scores = np.asarray(model.decision_function(matrix), dtype=np.float64)
    if scores.ndim == 1:
        scores = np.column_stack((-.5*scores, .5*scores))
    return scores


def _selection_metrics(y, scores, classes, task):
    if not len(y):
        return {"n": 0, "selection_metric": None}
    predicted = np.asarray(classes)[scores.argmax(axis=1)]
    present = np.unique(y)
    recalls = recall_score(y, predicted, labels=present, average=None, zero_division=0)
    info = {"n": len(y), "accuracy": float(accuracy_score(y, predicted)),
        "balanced_accuracy": float(np.mean(recalls)),
        "macro_f1": float(f1_score(y, predicted, labels=classes, average="macro", zero_division=0))}
    if task == "binary":
        info["auroc"] = float(roc_auc_score(y, scores[:,1]-scores[:,0])) if len(present) == 2 else None
        info["selection_metric"] = info["auroc"]
    else:
        info["selection_metric"] = info["macro_f1"]
    return info


def _binary_sample(records, limit, seed, char_limit=0, max_chars_per_text=0):
    def cost(row):
        return min(len(row["text"]),max_chars_per_text) if max_chars_per_text else len(row["text"])
    within_chars=not char_limit or sum(cost(row) for row in records)<=char_limit
    if (not limit or len(records) <= limit) and within_chars:
        return np.arange(len(records), dtype=np.int64)
    limit=limit or len(records)
    # Alternate human/AI first, then sources/models within each class. A flat
    # strata rotation would over-sample AI because it has many model strata.
    strata = defaultdict(list)
    for i, row in enumerate(records):
        key = (int(row["y_ai"]), _label(row.get("source")), _label(row.get("model")) if _trusted(row.get("mask_model")) else "coarse_only")
        priority = hashlib.sha256(f"{seed}:{row['id']}".encode()).digest()
        strata[key].append((priority, i))
    queues = defaultdict(deque)
    for key in sorted(strata):
        queues[key[0]].append(iter(i for _,i in sorted(strata[key])))
    selected = []
    selected_chars=0
    while any(queues.values()) and len(selected) < limit:
        for label in sorted(queues):
            while queues[label]:
                queue=queues[label].popleft()
                try:
                    index=next(queue)
                except StopIteration:
                    continue
                queues[label].append(queue)
                if char_limit and selected_chars+cost(records[index])>char_limit:
                    continue
                selected.append(index)
                selected_chars+=cost(records[index])
                break
            if len(selected) >= limit:
                break
    return np.asarray(sorted(selected), dtype=np.int64)


def _family_only_sample(records, indices, config):
    strata=defaultdict(list)
    for index in indices:
        row=records[index]
        key=(_label(row.get("family")),_label(row.get("source")),_label(row.get("domain")))
        priority=hashlib.sha256(f"family:{config.seed}:{row['id']}".encode()).digest()
        strata[key].append((priority,int(index)))
    queues=[(key[0],iter(i for _,i in sorted(strata[key]))) for key in sorted(strata)]
    selected=[];counts=Counter();used_chars=0
    while queues:
        remaining=[]
        for family,queue in queues:
            if config.max_family_only_rows_per_class and counts[family]>=config.max_family_only_rows_per_class:
                continue
            try:
                index=next(queue)
            except StopIteration:
                continue
            remaining.append((family,queue))
            text=records[index]["text"]
            chars=min(len(text),config.max_chars_per_text) if config.max_chars_per_text else len(text)
            if config.max_family_only_train_chars and used_chars+chars>config.max_family_only_train_chars:
                continue
            selected.append(index);counts[family]+=1;used_chars+=chars
        queues=remaining
    return np.asarray(sorted(selected),dtype=np.int64)


class EnglishStatisticalDetector:
    def __init__(self, config=None):
        self.config = config or StatisticalConfig()

    def fit(self, train_records, validation_records, dev_challenge_records=None, progress=None):
        train_records, validation_records = list(train_records), list(validation_records)
        challenge = list(dev_challenge_records or [])
        _check_records(train_records, "train")
        _check_records(validation_records, "validation")
        assert_disjoint(train_records, validation_records, "train", "validation")
        if challenge:
            _check_records(challenge, "dev_challenge")
            assert_disjoint(train_records, challenge, "train", "dev_challenge")
            assert_disjoint(validation_records, challenge, "validation", "dev_challenge")
        if len(np.unique(_targets(train_records, "binary"))) != 2:
            raise ValueError("binary training requires human and AI examples")
        started = time.monotonic()
        self.features_ = MultiChannelFeatures(self.config)
        binary_indices = _binary_sample(train_records, self.config.max_binary_train_rows, self.config.seed,
            self.config.max_binary_train_chars,self.config.max_chars_per_text)
        if len(np.unique(_targets([train_records[i] for i in binary_indices],"binary")))!=2:
            raise ValueError("configured binary training budget did not retain both classes")
        trusted_model=_head_mask(train_records,"model")
        trusted_family=_head_mask(train_records,"family")
        family_only_indices=_family_only_sample(train_records,np.flatnonzero(trusted_family & ~trusted_model),self.config)
        family_indices=np.union1d(family_only_indices,np.flatnonzero(trusted_family & trusted_model))
        union = np.union1d(np.union1d(binary_indices,np.flatnonzero(trusted_model)),family_indices)
        fit_records = [train_records[i] for i in union]
        binary_union_mask = np.isin(union, binary_indices)
        family_union_mask = np.isin(union, family_indices)
        self.training_ids_ = frozenset(_array(train_records,"id"))
        self.training_groups_ = frozenset(_array(train_records,"group_id")) - {""}
        self.training_hashes_ = frozenset(_array(train_records,"normalized_sha256")) - {""}
        self.validation_ids_ = frozenset(_array(validation_records,"id")) | frozenset(_array(challenge,"id"))
        self.validation_groups_ = (frozenset(_array(validation_records,"group_id")) | frozenset(_array(challenge,"group_id"))) - {""}
        self.validation_hashes_ = (frozenset(_array(validation_records,"normalized_sha256")) | frozenset(_array(challenge,"normalized_sha256"))) - {""}
        self.models_, self.classes_, self.selection_ = {}, {}, {}
        self.calibrators_, self.calibration_ = {}, {}
        model_families=defaultdict(set)
        for row in fit_records:
            if int(row["y_ai"])==1 and _trusted(row.get("mask_model")) and _trusted(row.get("mask_family")) and _known_label(row.get("model")) and _known_label(row.get("family")):
                model_families[_label(row["model"])].add(_label(row["family"]))
        self.model_to_family_={model:next(iter(families)) for model,families in model_families.items() if len(families)==1}
        if progress:
            progress({"phase":"features", "train_rows":len(train_records),"feature_fit_rows":len(fit_records),"binary_fit_rows":len(binary_indices)})
        with threadpool_limits(limits=self.config.cpu_threads):
            xtrain = self.features_.fit_transform(_texts(fit_records))
            dev_plan=_window_plan(_texts(validation_records),self.config)
            xdev = self.features_.transform(dev_plan["texts"])
            challenge_plan=_window_plan(_texts(challenge),self.config) if challenge else None
            xchallenge = self.features_.transform(challenge_plan["texts"]) if challenge else None
            if progress:
                progress({"phase":"features_ready", **self.features_.fit_info_})
            for task in ("binary", "family", "model"):
                train_mask = binary_union_mask if task == "binary" else (family_union_mask if task=="family" else _head_mask(fit_records,task))
                train_y = _targets(fit_records,task)[train_mask]
                classes = np.unique(train_y)
                if len(classes) < 2:
                    self.selection_[task] = {"available":False,"reason":"fewer_than_two_trusted_training_classes","train_rows":int(train_mask.sum())}
                    self.classes_[task] = []
                    continue
                self.classes_[task] = [int(c) for c in classes] if task == "binary" else [str(c) for c in classes]
                dev_y = _targets(validation_records,task)
                dev_mask = _head_mask(validation_records,task) & np.isin(dev_y,classes)
                if challenge:
                    ext_y = _targets(challenge,task)
                    ext_mask = _head_mask(challenge,task) & np.isin(ext_y,classes)
                else:
                    ext_y,ext_mask = np.asarray([]),np.asarray([],dtype=bool)
                candidates = (
                    ("linear_svc_C0.3", LinearSVC(C=.3, dual="auto", class_weight="balanced", max_iter=self.config.svc_max_iter, random_state=self.config.seed)),
                    ("linear_svc_C1.0", LinearSVC(C=1., dual="auto", class_weight="balanced", max_iter=self.config.svc_max_iter, random_state=self.config.seed)),
                    ("sgd_logloss_a1e-5", SGDClassifier(loss="log_loss", alpha=1e-5, class_weight="balanced", average=True,
                        max_iter=self.config.sgd_max_iter, tol=1e-4, random_state=self.config.seed, n_jobs=self.config.cpu_threads)),
                )
                best, best_score, history = None, -np.inf, []
                xfit = xtrain if train_mask.all() else xtrain[train_mask]
                estimated_solver_gib=(xtrain.data.nbytes+xtrain.indices.nbytes+xtrain.indptr.nbytes+
                    (0 if xfit is xtrain else xfit.data.nbytes+xfit.indices.nbytes+xfit.indptr.nbytes)+
                    24*xfit.nnz+16*len(classes)*xfit.shape[1])/1024**3+2.
                for name, estimator in candidates:
                    if name.startswith("linear_svc") and estimated_solver_gib>self.config.max_estimated_solver_gib:
                        entry={"candidate":name,"skipped":True,"reason":"estimated_sparse_solver_memory_above_budget",
                            "estimated_peak_gib":estimated_solver_gib,"budget_gib":self.config.max_estimated_solver_gib}
                        history.append(entry)
                        if progress: progress({"phase":"candidate_skipped","task":task,**entry})
                        continue
                    t0=time.monotonic()
                    with warnings.catch_warnings(record=True) as caught:
                        warnings.simplefilter("always",ConvergenceWarning)
                        estimator.fit(xfit,train_y)
                    dv = _selection_metrics(dev_y[dev_mask],_aggregate_window_scores(_score_matrix(estimator,xdev),dev_plan)[dev_mask],classes,task) if dev_mask.any() else {"n":0,"selection_metric":None}
                    ev = _selection_metrics(ext_y[ext_mask],_aggregate_window_scores(_score_matrix(estimator,xchallenge),challenge_plan)[ext_mask],classes,task) if challenge and ext_mask.any() else {"n":0,"selection_metric":None}
                    dscore,escore=dv["selection_metric"],ev["selection_metric"]
                    if escore is not None and dscore is not None:
                        selection_score = self.config.external_validation_weight*escore+(1-self.config.external_validation_weight)*dscore
                    else:
                        selection_score = escore if escore is not None else (dscore if dscore is not None else -np.inf)
                    entry={"candidate":name,"validation":dv,"dev_challenge":ev,
                        "selection_score":float(selection_score) if np.isfinite(selection_score) else None,
                        "fit_seconds":time.monotonic()-t0,"convergence_warnings":[str(w.message) for w in caught if issubclass(w.category,ConvergenceWarning)]}
                    history.append(entry)
                    if best is None or selection_score > best_score:
                        best,best_score=estimator,selection_score
                        selected_name=name
                    if progress:
                        progress({"phase":"candidate_ready","task":task,**entry})
                self.models_[task]=best
                self.selection_[task]={"available":True,"selected":selected_name,"classes":self.classes_[task],
                    "train_rows":int(train_mask.sum()),"train_support":dict(Counter(str(v) for v in train_y)),
                    "selection_rule":"0.70 external-development + 0.30 IID-development score when both available; binary AUROC, fine macro-F1; otherwise available development score; fixed candidate order resolves ties",
                    "estimated_svc_peak_gib":estimated_solver_gib,"candidates":history}
                del xfit
                gc.collect()
        self.fit_info_={"train_input_rows":len(train_records),"binary_fit_rows":len(binary_indices),
            "feature_fit_rows":len(fit_records),"all_trusted_fine_rows_retained":bool(len(family_indices)==int(trusted_family.sum())),
            "binary_sampling_method":"deterministic SHA-256, alternating human/AI first and source/model strata within each class, subject to row and bounded-character budgets",
            "binary_retained_class_support":dict(Counter(str(train_records[i]["y_ai"]) for i in binary_indices)),
            "all_trusted_model_rows_retained":True,
            "family_only_sampling":{"method":"deterministic SHA-256 priority with family/source/domain round-robin strata",
                "eligible_rows":int((trusted_family & ~trusted_model).sum()),"retained_rows":len(family_only_indices),
                "all_family_trusted_rows":int(trusted_family.sum()),"family_fit_rows":len(family_indices),
                "retained_family_support":dict(Counter(_label(train_records[i].get("family")) for i in family_indices)),
                "per_family_only_row_limit":self.config.max_family_only_rows_per_class,
                "family_only_char_budget":self.config.max_family_only_train_chars},
            "binary_fit_bounded_chars":sum(min(len(train_records[i]["text"]),self.config.max_chars_per_text) if self.config.max_chars_per_text else len(train_records[i]["text"]) for i in binary_indices),
            "validation_rows":len(validation_records),"dev_challenge_rows":len(challenge),
            "validation_window_coverage":dev_plan["summary"],"dev_challenge_window_coverage":challenge_plan["summary"] if challenge else None,
            "feature_fit":self.features_.fit_info_,"fit_seconds":time.monotonic()-started,
            "read_final_test_or_challenge":False}
        self.calibrated_=False
        return self

    def calibrate(self, calibration_records):
        records=list(calibration_records)
        _check_records(records,"calibration")
        for field,train_set,dev_set in (("id",self.training_ids_,self.validation_ids_),
            ("group_id",self.training_groups_,self.validation_groups_),
            ("normalized_sha256",self.training_hashes_,self.validation_hashes_)):
            observed={_label(row.get(field)) for row in records if row.get(field) not in (None,"")}
            if observed & (train_set | dev_set):
                raise ValueError(f"calibration overlaps train/development in {field}")
        with threadpool_limits(limits=self.config.cpu_threads):
            raw,coverage=self.predict_raw_scores(_texts(records),return_coverage=True)
            self.calibration_window_coverage_=coverage["summary"]
            for task,estimator in self.models_.items():
                classes=self.classes_[task]
                y=_targets(records,task)
                mask=_head_mask(records,task)&np.isin(y,classes)
                scores=raw[task][mask]
                if task == "binary":
                    if len(np.unique(y[mask]))!=2:
                        raise ValueError("calibration requires both binary classes")
                    margin=(scores[:,1]-scores[:,0]).reshape(-1,1)
                    calibrator=LogisticRegression(C=1000.,solver="lbfgs",max_iter=500,random_state=self.config.seed).fit(margin,y[mask])
                    self.calibrators_[task]=calibrator
                    self.calibration_[task]={"method":"Platt logistic regression on independent calibration margins", "rows":int(mask.sum()),
                        "support":dict(Counter(str(v) for v in y[mask])),"coefficient":float(calibrator.coef_[0,0]),"intercept":float(calibrator.intercept_[0]),"calibrated":True}
                elif len(y[mask]) >= 10 and len(np.unique(y[mask])) >= 2:
                    lookup={label:i for i,label in enumerate(classes)}
                    yi=np.asarray([lookup[v] for v in y[mask]],dtype=int)
                    def objective(log_temperature):
                        return float(log_loss(yi,softmax(scores/np.exp(log_temperature),axis=1),labels=np.arange(len(classes))))
                    optimum=minimize_scalar(objective,bounds=(-3.,3.),method="bounded")
                    temperature=float(np.exp(optimum.x))
                    self.calibrators_[task]=temperature
                    self.calibration_[task]={"method":"temperature scaling on independent trusted AI calibration rows", "rows":int(mask.sum()),
                        "temperature":temperature,"support":dict(Counter(str(v) for v in y[mask])),"calibrated":bool(optimum.success),
                        "fit_log_loss":float(optimum.fun),"fit_metrics_are_in_sample_calibration_not_test":True}
                else:
                    self.calibrators_[task]=1.
                    self.calibration_[task]={"method":"identity temperature fallback", "rows":int(mask.sum()),"temperature":1.,"calibrated":False,"reason":"insufficient_trusted_calibration_rows"}
        self.calibrated_=True
        return self

    def predict_raw_scores(self, texts, batch_size=None,return_coverage=False):
        """Uncalibrated NxK scores, available before calibration for selection.

        Binary columns are [-margin/2, +margin/2]; their difference is the
        classifier's original positive-AI margin. Fine columns follow classes_.
        """
        if isinstance(texts,str):
            raise TypeError("pass [text] for one text")
        values=list(texts)
        plan=_window_plan(values,self.config)
        batch_size=batch_size or self.config.feature_transform_batch_size
        if batch_size < 1:
            raise ValueError("batch_size must be positive")
        outputs={task:[] for task in ("binary","family","model")}
        with threadpool_limits(limits=self.config.cpu_threads):
            for start in range(0,len(plan["texts"]),batch_size):
                matrix=self.features_.transform(plan["texts"][start:start+batch_size])
                for task in outputs:
                    if task not in self.models_:
                        scores=np.empty((matrix.shape[0],0),dtype=float)
                    else:
                        scores=_score_matrix(self.models_[task],matrix)
                    outputs[task].append(scores)
        result={task:_aggregate_window_scores(np.concatenate(parts,axis=0),plan) if parts else np.empty((0,len(self.classes_.get(task,[])))) for task,parts in outputs.items()}
        coverage={"summary":plan["summary"],"window_counts":plan["counts"],"input_chars":plan["input_chars"],"covered_chars":plan["input_chars"].copy()}
        return (result,coverage) if return_coverage else result

    decision_scores=predict_raw_scores

    def probabilities_from_raw(self, raw_scores):
        if not self.calibrated_:
            raise RuntimeError("call calibrate on the independent calibration split before probability inference")
        outputs={}
        for task,scores in raw_scores.items():
            scores=np.asarray(scores,dtype=float)
            if not scores.size:
                outputs[task]=np.empty(scores.shape,dtype=float)
            elif task=="binary":
                outputs[task]=self.calibrators_[task].predict_proba((scores[:,1]-scores[:,0]).reshape(-1,1))
            else:
                outputs[task]=softmax(scores/self.calibrators_[task],axis=1)
        return outputs

    def predict_proba(self, texts, batch_size=None):
        return self.probabilities_from_raw(self.predict_raw_scores(texts,batch_size))

    def predict_records(self, texts, batch_size=None):
        values=list(texts) if not isinstance(texts,str) else [texts]
        probabilities=self.predict_proba(values,batch_size)
        results=[]
        for i,text in enumerate(values):
            p_ai=float(probabilities["binary"][i,1])
            decision="AI" if p_ai>=self.config.ai_accept_probability else ("human" if p_ai<=self.config.human_accept_probability else "uncertain")
            result={"p_ai":p_ai,"decision":decision,"family":"unknown","model":"unknown",
                "attribution_status":"insufficient_evidence","known_catalogue_only":True}
            if decision=="AI" and len(WORD.findall(text))>=self.config.attribution_min_word_tokens:
                for task,threshold in (("family",self.config.family_accept_probability),("model",self.config.model_accept_probability)):
                    p=probabilities[task][i]
                    if len(p) and self.calibration_.get(task,{}).get("calibrated") and float(p.max())>=threshold:
                        label=self.classes_[task][int(p.argmax())]
                        if task=="model" and (result["family"]=="unknown" or self.model_to_family_.get(label)!=result["family"]):
                            continue
                        result[task]=label
                        result[task+"_confidence"]=float(p.max())
                result["attribution_status"]="known_catalogue_match" if result["family"]!="unknown" else "unknown_or_low_confidence"
            results.append(result)
        return results

