def export_predictions(model, records, npz_path, jsonl_path=None):
    """Export development/calibration probabilities in original input order."""
    records=list(records)
    raw,coverage=model.predict_raw_scores(_texts(records),return_coverage=True)
    predictions=model.probabilities_from_raw(raw)
    arrays={"ids":_array(records,"id"),"group_ids":_array(records,"group_id"),
        "y_ai":np.asarray([int(row["y_ai"]) for row in records],dtype=np.int64),
        "sources":_array(records,"source"),"domains":_array(records,"domain"),
        "lengths":np.asarray([len(WORD.findall(row["text"])) for row in records],dtype=np.int32),
        "family_true":_array(records,"family"),"model_true":_array(records,"model"),
        "p_ai":predictions["binary"][:,1],"p_binary":predictions["binary"],
        "p_family":predictions["family"],"p_model":predictions["model"],
        "raw_binary":raw["binary"],"raw_family":raw["family"],"raw_model":raw["model"],
        "raw_binary_margin":raw["binary"][:,1]-raw["binary"][:,0],
        "window_counts":coverage["window_counts"],"input_chars":coverage["input_chars"],"covered_chars":coverage["covered_chars"],
        "binary_labels":np.asarray(["human","AI"]),"family_labels":np.asarray(model.classes_.get("family",[]),dtype=str),
        "model_labels":np.asarray(model.classes_.get("model",[]),dtype=str),
        "length_unit":np.asarray("word_like_tokens_regex")}
    for task in ("family","model"):
        arrays["mask_"+task]=_head_mask(records,task)&np.isin(arrays[task+"_true"],model.classes_.get(task,[]))
    path=Path(npz_path);path.parent.mkdir(parents=True,exist_ok=True)
    np.savez_compressed(path,**arrays)
    if jsonl_path:
        with Path(jsonl_path).open("w",encoding="utf-8") as stream:
            for i,row in enumerate(records):
                value={"id":_label(row["id"]),"group_id":_label(row.get("group_id")),"p_ai":float(arrays["p_ai"][i]),
                    "family_probs":predictions["family"][i].tolist(),"model_probs":predictions["model"][i].tolist(),
                    "raw_binary":raw["binary"][i].tolist(),"raw_family":raw["family"][i].tolist(),"raw_model":raw["model"][i].tolist(),
                    "mask_family":bool(arrays["mask_family"][i]),"mask_model":bool(arrays["mask_model"][i])}
                stream.write(json.dumps(value,ensure_ascii=False)+"\n")
    return {"rows":len(records),"npz":str(path),"label_order":model.classes_,"length_unit":"word_like_tokens_regex","window_coverage":coverage["summary"]}
